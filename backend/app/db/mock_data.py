def get_book_by_id(book_id: int) -> dict[str, Any] | None:
    """Return a book by ID, or None if it does not exist."""
    return next((book for book in BOOKS if book["id"] == book_id), None)


def get_books_by_category(category: str) -> list[dict[str, Any]]:
    """Return books matching a category (case-insensitive)."""
    return [
        book for book in BOOKS
        if book["category"].casefold() == category.casefold()
    ]


def search_books(keyword: str) -> list[dict[str, Any]]:
    """Search book titles, authors, categories, and descriptions."""
    query = keyword.casefold().strip()
    if not query:
        return BOOKS.copy()

    searchable_fields = ("title", "author", "category", "description")
    return [
        book for book in BOOKS
        if any(query in str(book[field]).casefold() for field in searchable_fields)
    ]
